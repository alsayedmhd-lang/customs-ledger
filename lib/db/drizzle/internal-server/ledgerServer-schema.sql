-- Ledger internal PostgreSQL schema, 2026-09-28.
-- Run only in the empty database "ledgerServer". This file creates no data.
-- SQLite remains the operational database. Only seven tables currently have
-- push/pull support in sync-worker.ts: clients, users, invoice_item_templates,
-- invoices, invoice_items, receipts, customer_ledger.

BEGIN;

CREATE TABLE clients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text,
  phone text,
  address text,
  tax_id text,
  notes text,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invoice_item_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description text NOT NULL,
  default_unit_price numeric(12,2) DEFAULT 0,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  item_code text UNIQUE
);

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  display_name text NOT NULL,
  display_name_ar text,
  display_name_en text,
  role text DEFAULT 'user',
  is_active boolean DEFAULT true,
  pending_approval boolean DEFAULT false,
  permissions jsonb,
  email text,
  phone text,
  whatsapp_api_key text,
  two_factor_email boolean DEFAULT false,
  two_factor_whatsapp boolean DEFAULT false,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  receiver_signature_base64 text,
  client_id integer REFERENCES clients(id),
  client_view_permissions jsonb
);

CREATE TABLE invoices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number text NOT NULL UNIQUE,
  client_id integer NOT NULL REFERENCES clients(id),
  issue_date text NOT NULL,
  due_date text,
  status text DEFAULT 'draft',
  subtotal numeric(12,2) DEFAULT 0,
  tax_rate numeric(7,2) DEFAULT 0,
  tax_amount numeric(12,2) DEFAULT 0,
  total numeric(12,2) DEFAULT 0,
  notes text,
  shipment_ref text,
  bill_of_lading text,
  package_count integer,
  shipment_weight numeric(14,3),
  port_of_entry text,
  importer_exporter_name text,
  advance_payment numeric(12,2) DEFAULT 0,
  created_by integer REFERENCES users(id),
  deleted_at timestamp,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invoice_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  description text NOT NULL,
  quantity numeric(14,3) NOT NULL,
  unit_price numeric(14,2) NOT NULL,
  total numeric(14,2) NOT NULL
);

CREATE TABLE receipts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_number text NOT NULL,
  client_id integer NOT NULL REFERENCES clients(id),
  invoice_id integer REFERENCES invoices(id) ON DELETE SET NULL,
  amount numeric(14,2) NOT NULL,
  payment_method text DEFAULT 'cash',
  notes text,
  receipt_date text NOT NULL,
  deleted_at timestamp,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  created_by integer REFERENCES users(id),
  status text NOT NULL DEFAULT 'issued'
);

CREATE TABLE customer_ledger (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id integer NOT NULL REFERENCES clients(id),
  invoice_id integer REFERENCES invoices(id),
  receipt_id integer REFERENCES receipts(id),
  entry_date text NOT NULL,
  entry_type text NOT NULL,
  description_ar text NOT NULL,
  description_en text NOT NULL,
  reference_type text NOT NULL,
  reference_number text,
  debit numeric(14,2) DEFAULT 0,
  credit numeric(14,2) DEFAULT 0,
  balance_impact numeric(14,2) DEFAULT 0,
  created_by integer REFERENCES users(id),
  created_at timestamp DEFAULT CURRENT_TIMESTAMP
);

-- The following tables mirror the current local structure but are not
-- transferred by the existing sync worker.

CREATE TABLE invoice_accounting (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  payments numeric(14,2) DEFAULT 0,
  transportation numeric(14,2) DEFAULT 0,
  labor numeric(14,2) DEFAULT 0,
  other_expenses numeric(14,2) DEFAULT 0,
  driver_name text,
  unload_location text,
  transportation_paid boolean DEFAULT false,
  labor_paid boolean DEFAULT false,
  other_expenses_paid boolean DEFAULT false,
  updated_at bigint
);

CREATE TABLE invoice_attachments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer REFERENCES invoices(id),
  declaration_number text NOT NULL,
  declaration_base_number text NOT NULL,
  file_name text NOT NULL,
  stored_name text NOT NULL,
  relative_path text NOT NULL,
  mime_type text,
  file_size bigint,
  category text NOT NULL DEFAULT 'other',
  storage_provider text NOT NULL DEFAULT 'local',
  created_by integer REFERENCES users(id),
  created_at bigint NOT NULL,
  deleted_at bigint
);

CREATE TABLE invoice_audit_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices(id),
  action text NOT NULL,
  user_id integer REFERENCES users(id),
  username text,
  user_email text,
  user_phone text,
  changes_json text,
  created_at bigint
);

CREATE TABLE otp_codes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id),
  code text NOT NULL,
  expires_at bigint NOT NULL,
  used_at bigint,
  created_at bigint
);

CREATE TABLE sync_queue (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type text NOT NULL,
  entity_id text NOT NULL,
  operation text NOT NULL,
  payload_json text,
  status text NOT NULL DEFAULT 'pending',
  retry_count integer NOT NULL DEFAULT 0,
  last_error text,
  synced_at bigint,
  created_at bigint,
  updated_at bigint
);

