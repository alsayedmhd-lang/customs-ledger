CREATE INDEX invoices_client_id_idx ON invoices(client_id);
CREATE INDEX invoice_items_invoice_id_idx ON invoice_items(invoice_id);
CREATE INDEX receipts_client_id_idx ON receipts(client_id);
CREATE INDEX receipts_invoice_id_idx ON receipts(invoice_id);
CREATE INDEX customer_ledger_client_id_idx ON customer_ledger(client_id);
CREATE INDEX sync_queue_status_idx ON sync_queue(status, retry_count);

COMMIT;

