  lock_footer_branding integer DEFAULT 0,
  login_footer_text text DEFAULT '',
  prevent_rebrand_to_another_company integer DEFAULT 0,
  license_status text DEFAULT 'not_configured',
  licensed_company_name text DEFAULT '',
